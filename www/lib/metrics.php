     * абсолютом, потому что «Знач.» у разных методик разного порядка: у
     * Басса-Дарки это целые −12…+6, у СМУ — дроби вида −1.73.
     */
    public const MID_BAND_FRAC = 0.05;
    public const MID_BAND_MIN = 0.5;

    /**
     * Контраст размеров кружков матрицы: НАСКОЛЬКО кружки отличаются друг от
     * друга, а не насколько они крупные (требование заказчика).
     *
     * Вес показателя (сумма когнитивного и эмоционального ответа) сначала
     * нормируется внутри профиля — от самого лёгкого показателя к самому
     * тяжёлому, — и уже эта относительная позиция растягивается вокруг середины:
     *   t' = 0.5 + (t − 0.5)·CONTRAST.
     * При 0 все кружки одного размера, при 1 разброс естественный (от R_MIN до
     * R_MAX), больше 1 — разница между «тяжёлым» и «лёгким» подчёркнута. Раньше
     * множитель был показателем степени (вес^POWER) и вместе с контрастом менял
     * сам размер: при 2 весь профиль становился мелким.
     */
    public const SIZE_CONTRAST = 1.0;

    /**
     * Пороги — НАСТРОЙКА, а не константа: оператор двигает пунктир прямо на
     * матрице (и правит числа в /setup.php), после чего кружки перекрашиваются,
     * а разделы отчёта пересобираются по новым границам. Значения приходят из
     * config.php (таблица settings) через configure(); пока его не позвали,
     * работают константы выше — расчёт всегда детерминирован.
     */
    private static ?array $conf = null;

    /** Применить настройки оператора (зовётся из np_boot()). */
    public static function configure(array $cfg): void {
        $num = static function ($v, float $def, float $min, float $max): float {
            if ($v === null || $v === '' || !is_numeric($v)) return $def;
            return max($min, min($max, (float) $v));
        };
        $low  = $num($cfg['MATRIX_LOW_PCT'] ?? null, self::LOW_PCT, 1.0, 98.0);
        $high = $num($cfg['MATRIX_HIGH_PCT'] ?? null, self::HIGH_PCT, 2.0, 99.0);
        if ($high <= $low) $high = min(99.0, $low + 1.0);   // порядок порогов держим сами
        self::$conf = [
            'low' => $low,
            'high' => $high,
            // Полоса медианы задаётся в процентах от предела шкалы физиологии.
            'mid_band_frac' => $num($cfg['MATRIX_MID_BAND_PCT'] ?? null, self::MID_BAND_FRAC * 100.0, 0.0, 50.0) / 100.0,
            'size_contrast' => $num($cfg['MATRIX_SIZE_POWER'] ?? null, self::SIZE_CONTRAST, 0.0, 6.0),
        ];
    }

    /** Текущее значение настройки (или константа по умолчанию). */
    private static function conf(string $key, float $default): float {
        return self::$conf === null ? $default : (float) (self::$conf[$key] ?? $default);
    }

    /**
     * Выполнить расчёт с ЗАФИКСИРОВАННЫМИ настройками — тот слой математики, по
     * которому уже сделана интерпретация (Interpret::mathLayer). Пороги общие для
     * сервиса и меняются мышью прямо на матрице, поэтому отчёт, собранный позже,
     * считался бы по новым правилам и расходился бы с текстом, который читал
     * клиент. Здесь настройки подменяются на время одного расчёта и возвращаются
     * обратно даже при исключении.
     *
     * @param array    $conf ['low'=>…,'high'=>…,'mid_band_frac'=>…,'size_contrast'=>…]
     * @param callable $fn   что посчитать с этими настройками
     */
    public static function withConf(array $conf, callable $fn) {
        $saved = self::$conf;
        $base = $saved ?? [
            'low' => self::LOW_PCT, 'high' => self::HIGH_PCT,
            'mid_band_frac' => self::MID_BAND_FRAC, 'size_contrast' => self::SIZE_CONTRAST,
        ];
        // Берём только знакомые ключи и только заполненные: снимок мог быть
        // сделан старой версией кода, где части настроек ещё не было.
        foreach (['low', 'high', 'mid_band_frac', 'size_contrast'] as $k) {
            if (isset($conf[$k]) && is_numeric($conf[$k])) $base[$k] = (float) $conf[$k];
        }
        self::$conf = $base;
        try {
            return $fn();
        } finally {
            self::$conf = $saved;
        }
    }

    /**
     * Настройки из сохранённого снимка (Interpret::mathLayer) в вид withConf().
     * Ключи снимка названы как поля расчёта (low_pct/high_pct), а не как
     * внутренние ключи настройки, — переводим здесь, в одном месте.
     */
    public static function confFromSnapshot(?array $snapshot): array {
        $c = $snapshot['conf'] ?? null;
        if (!is_array($c)) return [];
        $map = ['low_pct' => 'low', 'high_pct' => 'high',
                'mid_band_frac' => 'mid_band_frac', 'size_contrast' => 'size_contrast'];
        $out = [];
        foreach ($map as $from => $to) {
            if (isset($c[$from]) && is_numeric($c[$from])) $out[$to] = (float) $c[$from];
        }
        return $out;
    }

