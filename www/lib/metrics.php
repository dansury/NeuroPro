    /** Расшифровки каналов СМК для методики (общая таблица, если своей нет). */
    public static function smkMeanings(string $testKey = ''): array {
        return self::SMK_MEANING_BY_TEST[$testKey] ?? self::SMK_MEANING;
    }

    /** Практический смысл доминирующего параметра шкалы (или пустая строка). */
    public static function smkMeaning(string $smk, string $testKey = ''): string {
        $letter = self::dominant($smk);
        return $letter === '' ? '' : (string) (self::smkMeanings($testKey)[$letter] ?? '');
    }

    /**
     * Опорный факт: одна фраза, которую текст отчёта обязан соблюдать. Явно
     * называет и уровень, и направление физиологии — чтобы модель не могла
     * пересказать отрицательное «Знач.» как телесный отклик.
     */
    private static function fact(array $a): string {
        $lvl = sprintf('%s уровень (%s из %d, %s%%, %s по профилю — %d-я из шкал)',
            $a['level_label'], self::num($a['score']), $a['scale_max'], self::num($a['pct']),
            $a['rank_label'], (int) $a['rank']);
        if ($a['zna'] === null) {
            return $lvl . '; физиология не распознана — о телесной реакции не пишем';
        }
        $phys = match ($a['phys_state']) {
            'above' => $a['sig']
                ? 'тело откликается на тему достоверно сильнее обычного'
                : 'телесный отклик выше медианы, но нестабильный',
            'below' => $a['sig']
                ? 'тело на тему достоверно НЕ откликается — эмоционально не задевает'
                : 'телесного отклика на тему нет',
            default => 'телесный отклик у медианы — ни напряжения, ни явного спокойствия',
        };
        return $lvl . '; Знач. ' . self::num($a['zna']) . ' (' . $a['phys_label'] . ') — ' . $phys;
    }

    /**
     * ПОЧЕМУ выбрана опорная шкала первого шага. Формулировка честная: если
     * телесного отклика в профиле нет вовсе, опора остаётся когнитивной, и это
     * прямо названо, а не замаскировано (Конституция, принцип II).
     */
    public const FIRST_STEP_BASIS = [
        'proven'    => 'тело откликается на тему сильнее медианы, и отклонение достоверно — самый надёжный '
            . 'телесный сигнал в этом профиле',
        'weak'      => 'тело откликается сильнее медианы, но отклонение недостоверно — достовернее телесного '
            . 'сигнала в профиле нет',
        'calm'      => 'ни по одной шкале тело не откликается выше медианы, поэтому опора — самая нагруженная '
            . 'тема по ответам теста',
        'cognitive' => 'физиология по шкале не распознана, поэтому опора — самая нагруженная тема по ответам теста',
    ];

    /**
     * ОПОРА ПЕРВОГО ШАГА — шкала, вокруг которой строится единственное конкретное
     * действие в конце отчёта («с чего начать»). Заказчик просит, чтобы этот шаг
     * опирался на самые достоверные данные физиологии и давал наибольший эффект
     * для состояния клиента, — значит, выбор шкалы такая же математика, как
     * уровень и раздел, и делается здесь (Конституция, принцип I). Нейросеть
     * получает готовый выбор и только превращает его в действие.
     *
     * Порядок отбора:
     *  1. шкалы, где тело откликается выше медианы: именно там разгрузка меняет
     *     состояние. Сначала достоверные (p<0.01 раньше p<0.05), потом остальные;
     *  2. внутри тира — по весу показателя (сумма когнитивного и эмоционального
     *     ответа, тот же вес, что задаёт размер кружка на матрице): чем тяжелее
     *     тема, тем больше даёт работа с ней;
     *  3. дальше — выраженность в ответах и номер шкалы: выбор обязан быть
     *     воспроизводимым, а не зависеть от порядка обхода;
     *  4. если телесного отклика выше медианы нет ни у одной шкалы, опорой
     *     становится самая нагруженная шкала отчёта, и основание об этом честно
     *     говорит.
     *
     * Шкала, выпавшая из отчёта (категория «skip»), опорой быть не может:
     * действие нельзя строить на теме, о которой в отчёте нет ни слова.
     *
     * @return array|null null — если в разделы отчёта не попала ни одна шкала
     */
    public static function firstStep(array $axes): ?array {
        $pool = [];
        foreach ($axes as $i => $a) {
            if ($a['category'] !== 'skip') $pool[$i] = $a;
        }
        if (!$pool) return null;

        $above = array_filter($pool, static fn ($a) => $a['phys_state'] === 'above');
        $pick = $above ?: $pool;
        // Достоверность различает кандидатов только там, где тело откликается:
        // ниже медианы «достоверно» значит достоверное ОТСУТСТВИЕ отклика, и
        // ставить такую шкалу выше остальных было бы подменой смысла.
        $tier = static function (array $a) use ($above): int {
            if (!$above || !$a['sig']) return 0;
            return ($a['p'] !== null && $a['p'] < 0.01) ? 2 : 1;
        };
        uasort($pick, static fn (array $x, array $y): int => $tier($y) <=> $tier($x)
            ?: (float) $y['weight'] <=> (float) $x['weight']
            ?: (float) $y['pct'] <=> (float) $x['pct']
            ?: (int) $x['n'] <=> (int) $y['n']);

        $idx = (int) array_key_first($pick);
        $a = $axes[$idx];
        $basis = match (true) {
            $a['phys_state'] === 'above' => $a['sig'] ? 'proven' : 'weak',
            $a['zna'] === null           => 'cognitive',
            default                      => 'calm',
        };
        return [
            'index' => $idx,
            'label' => $a['label'],
            'basis' => $basis,
            'basis_label' => self::FIRST_STEP_BASIS[$basis],
            'category' => $a['category'],
            'category_title' => $a['category_title'],
            'sig' => (bool) $a['sig'],
            'p_label' => $a['p_label'],
            'smk_label' => $a['smk_label'],
            'smk_meaning' => $a['smk_meaning'],
            'fact' => $a['fact'],
            'text' => $a['label'] . ' — ' . self::FIRST_STEP_BASIS[$basis],
        ];
    }

    private static function floatOrNull($v): ?float {
        return ($v === null || $v === '') ? null : (float) $v;
    }

    /** Компактное число: 9.0 → «9», −3.5 → «-3.5». */
    public static function num(float $v): string {
        return rtrim(rtrim(number_format($v, 1, '.', ''), '0'), '.');
    }
