                . 'по этому поводу — во время инцидента или уже после него',
            'X' => 'ведущий канал — психическое напряжение (ЭЭГ): человек реагирует с холодной головой '
                . 'и полным пониманием происходящего',
            'Z' => 'ведущий канал — мышечная реакция (нажатие стилусом): человек действует решительно, '
