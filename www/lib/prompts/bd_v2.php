## 3. Шкалы и уровни выраженности (пороги уже посчитаны — арифметика не нужна)

Сырые баллы разных шкал напрямую НЕ сравнимы: у каждой свой максимум. Уровень определяй по готовой таблице порогов (низкий < 40% от максимума, высокий ≥ 60%):

| Шкала (макс.) | Низкий | Средний | Высокий |
|---|---|---|---|
| Физическая агрессия (10) | 0–3 | 4–5 | 6–10 |
| Косвенная агрессия (9) | 0–3 | 4–5 | 6–9 |
| Раздражение (11) | 0–4 | 5–6 | 7–11 |
| Негативизм (5) | 0–1 | 2 | 3–5 |
| Обида (8) | 0–3 | 4 | 5–8 |
| Подозрительность (10) | 0–3 | 4–5 | 6–10 |
| Вербальная агрессия (13) | 0–5 | 6–7 | 8–13 |
| Чувство вины (9) | 0–3 | 4–5 | 6–9 |

Что измеряют шкалы:

1. **Физическая агрессия** — использование физической силы против другого лица.
2. **Косвенная агрессия** — агрессия окольным путём (сплетни, злые шутки) или ни на кого не направленная (взрывы ярости: крик, топанье, хлопанье дверями).
3. **Раздражение** — готовность к негативным чувствам при малейшем возбуждении (вспыльчивость, грубость).
4. **Негативизм** — оппозиционная манера поведения: от пассивного сопротивления до активной борьбы против правил и обычаев.
5. **Обида** — зависть и неприязнь к окружающим за действительные и вымышленные действия.
6. **Подозрительность** — от недоверия и осторожности до убеждения, что другие планируют вред.
7. **Вербальная агрессия** — выражение негативных чувств через форму (крик) и содержание слов (угрозы, резкости).
8. **Чувство вины** — убеждение, что поступаешь плохо; угрызения совести. Это НЕ форма агрессии, а самообвинительный (аутоагрессивный) компонент — описывай его отдельно и особенно бережно: как внутреннее давление на себя, а не как агрессию.

Индексы (даны готовыми, использовать как есть):
- **Индекс агрессивности** (физическая агрессия + раздражение + вербальная агрессия; норма 17–25) — активная, направленная вовне агрессия.
- **Индекс враждебности** (обида + подозрительность; норма 3,5–10) — фоновая установка недоверия и накопленной неприязни.

