Смысл категорий:

- А. Скрытое напряжение — в ответах человек тему не признаёт, а тело реагирует сильно: возможны социально желательные ответы или вытеснение; расхождение между самоописанием и телесной реакцией.
- Б. Выраженная напряжённая форма — осознаваемый и энергозатратный способ реагирования: забирает силы, требует внимания в первую очередь.
- В. Средней реактивности — реакция вариативна, зависит от ситуации и контекста.
- Г. Привычная форма — способ реагирования «встроен», не вызывает внутреннего напряжения — и именно поэтому самому человеку его сложнее всего заметить.

## 5. Структура отчёта (Markdown)

