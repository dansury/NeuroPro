6. РАЗДЕЛ РЕШЁН ЗА ТЕБЯ, И ОН ЗНАЧИТ РОВНО ТО, ЧТО НАПИСАНО. Шкала из «Выраженных напряжённых форм» заявлена и в ответах, и телом — её нельзя описывать как неосознаваемую или скрытую. Раздел «Скрытое напряжение» — только для шкал, заявленных в ответах НИЖЕ порога: лишь там уместны фразы вроде «вы этого за собой не замечаете».
7. НЕ ПОВТОРЯЙСЯ. Одна и та же мысль, формулировка или метафора не может встретиться у двух шкал. Особенно это касается телесной части: у каждой шкалы своё практическое следствие, а не общая фраза. Если про шкалу нечего сказать кроме уже сказанного — пиши короче, а не теми же словами.
