## Регрессия
Возвращение к более ранним, привычным с детства формам поведения: эмоциональным вспышкам, обвинениям других, демонстрации беспомощности. Это срабатывает, потому что демонстрация слабости часто вызывает у окружающих желание поддержать и защитить. Регрессия снимает с вас бремя ответственности — как в детстве, когда за многое отвечали родители. Краткосрочно это работает, но при злоупотреблении разрушает отношения, репутацию и приводит к накоплению нерешенных проблем.

## Реактивное образование
Превращение истинных чувств в их противоположность. Вы испытываете страх перед чем-то, но демонстративно это критикуете. Завидуете чужому успеху, но публично высмеиваете его. Механизм часто выдает себя неадекватностью реакции и периодическими «прорывами» настоящего отношения. Это не устраняет внутренний конфликт, а лишь маскирует его, создавая дополнительное напряжение и мешая принимать взвешенные решения.

## Интеллектуализация
Нейтрализация тревоги, боли или гнева через уход в анализ, теории и абстрактные концепции. Вместо того чтобы прожить чувства, вы погружаетесь в изучение моделей и систем. Такое поведение выглядит зрелым и рациональным, что делает защиту социально привлекательной. Интеллектуализация действительно помогает снизить влияние эмоций на решения, но длительное применение приводит к отрыву от реальности, потере способности понимать мотивы людей и параличу через бесконечный анализ.

