## Замещение
Перенаправление подавленных эмоций — чаще всего гнева — с недоступного объекта на более безопасный. Не можете выразить злость тому, кто ее вызвал, и срываетесь на тех, кто под рукой и не может ответить. Это временно снижает напряжение, но не устраняет причину, а только создает новые конфликты и цепную реакцию негатива в вашем окружении.

